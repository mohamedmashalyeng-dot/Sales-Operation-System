import { campaignById, sourceByName } from "@/config/attribution";

type LeadSeed = Omit<
  Lead,
  | "channel"
  | "platform"
  | "acquisitionDate"
  | "originalOwnerId"
  | "campaign"
  | "campaignId"
  | "utmSource"
  | "utmMedium"
  | "utmCampaign"
> & {
  channel?: string;
  platform?: string;
  acquisitionDate?: string;
  originalOwnerId?: string;
  campaignId?: string;
  campaign?: string;
  utmSource?: string;
  utmMedium?: string;
  utmCampaign?: string;
};

/** Enriches a lead seed with channel/platform + campaign name derived from source. */
function lead(seed: LeadSeed): Lead {
  const source = sourceByName(seed.source);
  return {
    ...seed,
    channel: seed.channel ?? source?.channel ?? "Direct",
    platform: seed.platform ?? source?.platform ?? "Manual",
    acquisitionDate: seed.acquisitionDate ?? seed.createdAt,
    originalOwnerId: seed.originalOwnerId ?? seed.ownerId,
    campaign: seed.campaignId ? campaignById(seed.campaignId)?.name : seed.campaign,
  };
}

